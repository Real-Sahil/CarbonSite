// lib/reports/cbam-xml.ts
// CBAM (Carbon Border Adjustment Mechanism) XML Report Generator
//
// Implements the transitional reporting format per EU Implementing Reg 2023/1773
// and anticipates the UK CBAM framework (expected April 2027+).
//
// Covered goods (EU CBAM Annex I):
//   Cement (CN 2523), Iron/Steel (CN 72-73), Aluminium (CN 76),
//   Fertilisers (CN 28/31), Electricity (CN 2716), Hydrogen (CN 2804)

export interface CbamInstallation {
  name: string;
  country: string; // ISO 3166-1 alpha-2 (e.g. "DE", "CN", "TR")
  latitude?: number;
  longitude?: number;
}

export interface CbamGoodsItem {
  cnCode: string;        // Combined Nomenclature code (4-digit prefix)
  description: string;
  quantityTonnes: number;
  directEmbeddedCo2eTonnes: number;   // Direct process + energy emissions
  indirectEmbeddedCo2eTonnes: number; // Indirect (electricity) emissions
  carbonPricePaidGbp: number;         // Carbon cost already borne in origin country
  installation?: CbamInstallation;
}

export interface CbamReportData {
  declarantName: string;
  declarantEori?: string; // e.g. "GB123456789000"
  reportingPeriodLabel: string; // e.g. "Q1 2025"
  periodStart: Date;
  periodEnd: Date;
  submissionDate: Date;
  goodsItems: CbamGoodsItem[];
}

