// ── XML generation ────────────────────────────────────────────────────────────

function esc(s: string | number): string {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function fmtDate(d: Date): string {
  return d.toISOString().slice(0, 10);
}

function fmtN(n: number, dp = 6): string {
  return n.toFixed(dp);
}

/**
 * Generates a CBAM transitional-period XML report string.
 * Pure function — no database access. Pass pre-aggregated data from the worker.
 */
export function generateCbamXml(data: CbamReportData): string {
  const totalDirect   = data.goodsItems.reduce((s, g) => s + g.directEmbeddedCo2eTonnes, 0);
  const totalIndirect = data.goodsItems.reduce((s, g) => s + g.indirectEmbeddedCo2eTonnes, 0);
  const totalEmbedded = totalDirect + totalIndirect;

  const lines: string[] = [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<!--`,
    `  CBAM Transitional Period Report`,
    `  Reporting period : ${esc(data.reportingPeriodLabel)}`,
    `  Generated by     : CarbonSite`,
    `  Generated at     : ${fmtDate(data.submissionDate)}`,
    `  Regulation refs  : EU Reg 2023/956 + Implementing Reg 2023/1773`,
    `  Note             : UK CBAM applies from April 2027; use EU format until`,
    `                     HMRC publishes the UK XML schema.`,
    `-->`,
    `<CBAMReport`,
    `    xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"`,
    `    schemaVersion="1.0">`,
    ``,
    `  <!-- ── Declarant ──────────────────────────────────────────────── -->`,
    `  <Declarant>`,
    `    <Name>${esc(data.declarantName)}</Name>`,
  ];

  if (data.declarantEori) {
    lines.push(`    <EORI>${esc(data.declarantEori)}</EORI>`);
  } else {
    lines.push(`    <!-- EORI: required for final CBAM submission — obtain from HMRC/EORI GB portal -->`);
  }

  lines.push(
    `  </Declarant>`,
    ``,
    `  <!-- ── Reporting period ───────────────────────────────────────── -->`,
    `  <ReportingPeriod>`,
    `    <Label>${esc(data.reportingPeriodLabel)}</Label>`,
    `    <StartDate>${fmtDate(data.periodStart)}</StartDate>`,
    `    <EndDate>${fmtDate(data.periodEnd)}</EndDate>`,
    `  </ReportingPeriod>`,
    ``,
    `  <SubmissionDate>${fmtDate(data.submissionDate)}</SubmissionDate>`,
    ``,
    `  <!-- ── Summary totals ─────────────────────────────────────────── -->`,
    `  <Summary>`,
    `    <TotalGoodsItems>${data.goodsItems.length}</TotalGoodsItems>`,
    `    <TotalDirectEmbeddedCO2eTonnes>${fmtN(totalDirect)}</TotalDirectEmbeddedCO2eTonnes>`,
    `    <TotalIndirectEmbeddedCO2eTonnes>${fmtN(totalIndirect)}</TotalIndirectEmbeddedCO2eTonnes>`,
    `    <TotalEmbeddedCO2eTonnes>${fmtN(totalEmbedded)}</TotalEmbeddedCO2eTonnes>`,
    `  </Summary>`,
    ``,
    `  <!-- ── Goods items ────────────────────────────────────────────── -->`,
    `  <GoodsItems>`,
  );

  for (const item of data.goodsItems) {
    const total     = item.directEmbeddedCo2eTonnes + item.indirectEmbeddedCo2eTonnes;
    const specific  = item.quantityTonnes > 0 ? total / item.quantityTonnes : 0;

    lines.push(`    <GoodsItem>`);
    lines.push(`      <CNCode>${esc(item.cnCode)}</CNCode>`);
    lines.push(`      <Description>${esc(item.description)}</Description>`);

    if (item.installation) {
      lines.push(`      <Installation>`);
      lines.push(`        <Name>${esc(item.installation.name)}</Name>`);
      lines.push(`        <CountryOfOrigin>${esc(item.installation.country)}</CountryOfOrigin>`);
      if (item.installation.latitude != null) {
        lines.push(`        <Coordinates>`);
        lines.push(`          <Latitude>${fmtN(item.installation.latitude, 4)}</Latitude>`);
        lines.push(`          <Longitude>${fmtN(item.installation.longitude ?? 0, 4)}</Longitude>`);
        lines.push(`        </Coordinates>`);
      }
      lines.push(`      </Installation>`);
    }

    lines.push(
      `      <ImportedQuantity>`,
      `        <Value>${fmtN(item.quantityTonnes, 3)}</Value>`,
      `        <Unit>tonne</Unit>`,
      `      </ImportedQuantity>`,
      `      <EmbeddedEmissions>`,
      `        <Direct>`,
      `          <CO2eTonnes>${fmtN(item.directEmbeddedCo2eTonnes)}</CO2eTonnes>`,
      `        </Direct>`,
      `        <Indirect>`,
      `          <CO2eTonnes>${fmtN(item.indirectEmbeddedCo2eTonnes)}</CO2eTonnes>`,
      `        </Indirect>`,
      `        <Total>`,
      `          <CO2eTonnes>${fmtN(total)}</CO2eTonnes>`,
      `          <SpecificCO2eTonnesPerTonne>${fmtN(specific)}</SpecificCO2eTonnesPerTonne>`,
      `        </Total>`,
      `      </EmbeddedEmissions>`,
      `      <CarbonPriceDue>`,
      `        <Currency>GBP</Currency>`,
      `        <Value>${fmtN(item.carbonPricePaidGbp, 2)}</Value>`,
      `      </CarbonPriceDue>`,
      `    </GoodsItem>`,
    );
  }

  lines.push(
    `  </GoodsItems>`,
    `</CBAMReport>`,
  );

  return lines.join("\n");
}

/**
 * Validates a CbamGoodsItem list for the most common submission errors.
 * Returns a list of human-readable error strings (empty = valid).
 */
export function validateCbamItems(items: CbamGoodsItem[]): string[] {
  const errors: string[] = [];
  if (items.length === 0) {
    errors.push("No CBAM goods items found — ensure Scope 3 purchased-goods records include material type metadata.");
    return errors;
  }
  for (const [i, item] of items.entries()) {
    const prefix = `Item ${i + 1} (${item.cnCode})`;
    if (!item.cnCode || !/^\d{4}$/.test(item.cnCode)) {
      errors.push(`${prefix}: CN code must be exactly 4 digits.`);
    }
    if (item.quantityTonnes <= 0) {
      errors.push(`${prefix}: Imported quantity must be > 0 tonnes.`);
    }
    if (item.directEmbeddedCo2eTonnes < 0) {
      errors.push(`${prefix}: Direct embedded CO₂e cannot be negative.`);
    }
    if (item.indirectEmbeddedCo2eTonnes < 0) {
      errors.push(`${prefix}: Indirect embedded CO₂e cannot be negative.`);
    }
    if (item.carbonPricePaidGbp < 0) {
      errors.push(`${prefix}: Carbon price paid cannot be negative.`);
    }
    if (item.installation && item.installation.country.length !== 2) {
      errors.push(`${prefix}: Country of origin must be a 2-letter ISO code.`);
    }
  }
  return errors;
}
